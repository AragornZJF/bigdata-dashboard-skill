#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Reverse of make_xlsx_template.py: convert a filled Excel template back to JSON.

Usage:
  python xlsx_to_json.py <filled.xlsx> [output.json]

Reads the hidden "_meta" sheet (path, kind, sheet, sub) written by
make_xlsx_template.py and reconstructs the original data structure.
"""
import json
import sys
import os
from openpyxl import load_workbook


def set_path(d, path, value):
    parts = path.split(".")
    cur = d
    for p in parts[:-1]:
        cur = cur.setdefault(p, {})
    cur[parts[-1]] = value


def maybe_json(v):
    if isinstance(v, str):
        s = v.strip()
        if s.startswith("[") or s.startswith("{"):
            try:
                return json.loads(s)
            except Exception:
                pass
    return v


def main():
    if len(sys.argv) < 2:
        print("usage: xlsx_to_json.py <filled.xlsx> [output.json]")
        sys.exit(1)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.splitext(src)[0] + ".json"
    wb = load_workbook(src, data_only=True)
    if "_meta" not in wb.sheetnames:
        print("ERROR: _meta sheet missing; not generated by make_xlsx_template.py")
        sys.exit(1)

    meta = []
    for row in wb["_meta"].iter_rows(min_row=2, values_only=True):
        if row[0] is None:
            continue
        meta.append((row[0], row[1], row[2], row[3] or ""))

    result = {}
    for path, kind, sheet, sub in meta:
        ws = wb[sheet]
        if kind == "scalar":
            for row in ws.iter_rows(min_row=2, values_only=True):
                if row[0] == path:
                    set_path(result, path, maybe_json(row[1]))
                    break
        elif kind == "objects":
            keys = [c.value for c in ws[1]]
            arr = []
            for r in range(2, ws.max_row + 1):
                obj = {}
                for ci, k in enumerate(keys, 1):
                    val = ws.cell(r, ci).value
                    if val is not None and val != "":
                        obj[k] = maybe_json(val)
                if obj:
                    arr.append(obj)
            set_path(result, path, arr)
        elif kind == "arrays":
            if sub == "scalar":
                arr = [maybe_json(ws.cell(r, 1).value)
                       for r in range(2, ws.max_row + 1)
                       if ws.cell(r, 1).value not in (None, "")]
                set_path(result, path, arr)
            else:
                maxc = ws.max_column
                arr = []
                for r in range(2, ws.max_row + 1):
                    row = [ws.cell(r, c).value for c in range(1, maxc + 1)]
                    if all(v in (None, "") for v in row):
                        continue
                    arr.append([maybe_json(v) if v not in (None, "") else "" for v in row])
                set_path(result, path, arr)
        elif kind == "json":
            txt = ws["A1"].value
            try:
                set_path(result, path, json.loads(txt))
            except Exception as e:
                print("WARN: json parse failed for", path, "->", e)

    json.dump(result, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("written:", out, "fields:", len(result))


if __name__ == "__main__":
    main()
